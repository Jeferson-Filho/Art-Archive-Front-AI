"use client";

import { AlertCircle, ChevronDown, ChevronUp, ExternalLink, Loader2Icon, Sparkles } from "lucide-react";
import React, { useLayoutEffect, useRef, useState } from "react";
import SkeletonLoader from "../../../../../components/skeletonLoader";
import { themeTailwindColorsToHex } from "../../../../util/converters";
import { InsightCardState, TextBlock } from "./types";
import { INSIGHT_CARD_SOURCE } from "./useInsightCard";

// Exact wordings required by the specification
const DISCLOSURE = "This content was generated by artificial intelligence and may contain inaccuracies."; // RF-008
const STANDARD_ERROR = "Was not possible to generate an educational text for this artwork."; // RF-005, RF-007
const TIMEOUT_ERROR = "The request took too long. Please try again later."; // RF-007 scenario 3

// About six lines of body text (text-md, leading-relaxed: 16px x 1.625) — RF-005 scenario 4
const COLLAPSED_HEIGHT_PX = 156;

/**
 * Insight Card (doc 04 §3) — a single "Context information" section holding
 * the historical context and comparative analysis as paragraphs, never as
 * separately titled subsections (RF-005). Three states: loading, displayed,
 * error (doc 08, §6).
 *
 * The status sits on the heading row, so the loading indicator appears as
 * soon as the section does (RNF-007).
 */
export default function InsightCard({ state }: { state: InsightCardState }) {
  return (
    <section className="w-full flex flex-col gap-2">
      {/* Title outside the card, as the page's "Artist" and "Description" blocks do */}
      <div className="flex items-center justify-between gap-4">
        <h2 className="text-lg font-semibold">Context information</h2>
        <div className="flex items-center gap-3">
          {state.status === "loading" && (
            <div className="flex items-center gap-2 text-sm text-silver-gray-lighter">
              <Loader2Icon size={18} className="animate-spin" />
              <span>Generating…</span>
            </div>
          )}
          {INSIGHT_CARD_SOURCE === "mock" && (
            <span className="text-xs font-semibold uppercase tracking-wide bg-golden-yellow/20 text-golden-yellow-darker px-2 py-0.5 rounded">
              Mock data
            </span>
          )}
        </div>
      </div>

      <div className="flex flex-col gap-4 border-4 border-golden-yellow rounded-2xl px-6 py-4">
        {state.status === "loading" && <LoadingBody />}
        {state.status === "displayed" && <DisplayedBody blocks={state.blocks} />}
        {state.status === "error" && (
          <p className="flex items-start gap-2 text-md">
            <AlertCircle size={20} className="shrink-0 mt-0.5 text-golden-yellow-darker" />
            {state.reason === "timeout" ? TIMEOUT_ERROR : STANDARD_ERROR}
          </p>
        )}
      </div>
    </section>
  );
}

function LoadingBody() {
  return (
    <div className="flex flex-col gap-3">
      <p className="text-sm text-silver-gray-lighter">
        Preparing the historical context and comparative analysis of this artwork. On a first visit this can take up to
        a minute.
      </p>
      {["w-full", "w-11/12", "w-4/6"].map((width) => (
        <SkeletonLoader
          key={width}
          cssClass={`h-4 ${width}`}
          baseColor="bg-gray-200"
          shimmerColor={themeTailwindColorsToHex["almost-white"]}
        />
      ))}
    </div>
  );
}

function DisplayedBody({ blocks }: { blocks: TextBlock[] }) {
  const contentRef = useRef<HTMLDivElement>(null);
  const [isLong, setIsLong] = useState(false);
  const [isExpanded, setIsExpanded] = useState(false);

  // Measured before paint, so long content never flashes in full before collapsing.
  // Re-measured on resize: a narrower card wraps into more lines.
  useLayoutEffect(() => {
    const content = contentRef.current;
    if (!content) return;

    const measure = () => setIsLong(content.scrollHeight > COLLAPSED_HEIGHT_PX);
    measure();
    const observer = new ResizeObserver(measure);
    observer.observe(content);
    return () => observer.disconnect();
  }, [blocks]);

  const isCollapsed = isLong && !isExpanded;

  return (
    <>
      {/* Outside the collapsible area: the notice is never hidden (RF-008) */}
      <p className="flex items-start gap-2 text-sm text-silver-gray-lighter">
        <Sparkles size={16} className="shrink-0 mt-0.5 text-golden-yellow-dark" />
        {DISCLOSURE}
      </p>

      <div className="relative">
        <div
          ref={contentRef}
          className="flex flex-col gap-4 overflow-hidden"
          style={isCollapsed ? { maxHeight: COLLAPSED_HEIGHT_PX } : undefined}
        >
          {blocks.map((block, index) => (
            <div key={index} className="flex flex-col gap-3">
              {toParagraphs(block.text).map((paragraph, paragraphIndex) => (
                <p key={paragraphIndex} className="text-md leading-relaxed">
                  {paragraph}
                </p>
              ))}
              {block.sources.length > 0 && <SourceList sources={block.sources} />}
            </div>
          ))}
        </div>
        {isCollapsed && (
          <div className="pointer-events-none absolute inset-x-0 bottom-0 h-12 bg-gradient-to-t from-almost-white to-transparent" />
        )}
      </div>

      {isLong && (
        // Overrides the global `button` style in globals.css (full width, black fill)
        <button
          type="button"
          onClick={() => setIsExpanded((expanded) => !expanded)}
          className="self-start inline-flex items-center gap-1 w-fit h-auto px-0 rounded-none bg-transparent hover:bg-transparent text-sm font-semibold text-golden-yellow-darker hover:underline focus-visible:underline"
        >
          {isExpanded ? "See less" : "See more"}
          {isExpanded ? <ChevronUp size={16} /> : <ChevronDown size={16} />}
        </button>
      )}
    </>
  );
}

// Listed beneath the block they support (RF-010 scenario 1)
function SourceList({ sources }: { sources: string[] }) {
  return (
    <div className="flex flex-col gap-1 text-sm">
      <p className="font-semibold">Sources</p>
      <ul className="flex flex-col gap-1">
        {sources.map((url) => (
          <li key={url}>
            <a
              href={url}
              target="_blank"
              rel="noreferrer"
              className="inline-flex items-center gap-1 text-golden-yellow-darker hover:underline break-all"
            >
              <ExternalLink size={14} className="shrink-0" />
              {displayUrl(url)}
            </a>
          </li>
        ))}
      </ul>
    </div>
  );
}

function toParagraphs(text: string): string[] {
  return text
    .split(/\n+/)
    .map((paragraph) => paragraph.trim())
    .filter(Boolean);
}

function displayUrl(url: string): string {
  try {
    const { hostname, pathname } = new URL(url);
    return (hostname + pathname).replace(/\/$/, "");
  } catch {
    return url;
  }
}
